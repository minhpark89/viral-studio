import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { _electron as electron } from 'playwright';
import { Store } from '../server/store.js';

const root=path.resolve('.verification',`media-flow-ui-${Date.now()}`);
const source=JSON.parse(await fs.readFile('D:/DROPSHIP/Viral Studio Data/workspace/studio.json','utf8'));
const recent=source.jobs.filter(job=>job.type==='news'&&job.status==='completed').sort((a,b)=>Date.parse(b.finishedAt)-Date.parse(a.finishedAt)).slice(0,3);
const store=new Store(root);
const project=store.createProject('Media flow QA');
store.state.settings.queuePaused=true;
store.state.settings.content.autoPublishNews=false;
const researchIds=new Set(recent.map(job=>job.production.researchId));
store.state.researchResults=source.researchResults.filter(r=>researchIds.has(r.id)).map(r=>({...r,projectId:project.id}));
store.state.jobs=recent.map(job=>({...job,projectId:project.id}));
const mediaIds=new Set(recent.flatMap(job=>[job.mediaId,job.payload.presenterMediaId,job.payload.avatarMediaId,...job.payload.imageMediaIds]));
store.state.media=source.media.filter(media=>mediaIds.has(media.id)||media.mediaType==='page-avatar').map(media=>({...media,projectId:media.mediaType==='page-avatar'?null:project.id}));
const fresh=store.add('researchResults',{projectId:project.id,headline:'Fresh test report',topic:'Fresh test report',contentSource:'llm',articles:[{id:randomUUID(),title:'Current source',publishedAt:new Date(Date.now()-3600000).toISOString()}],imageQueries:[],warnings:[]});
store.save();
const env={...process.env,STUDIO_DATA_DIR:root};delete env.ELECTRON_RUN_AS_NODE;
const staged=process.env.MEDIA_FLOW_EXE;
const application=await electron.launch({executablePath:staged?path.resolve(staged):path.resolve('node_modules/electron/dist/electron.exe'),args:[...(staged?[]:['.']),`--user-data-dir=${path.join(root,'electron-profile')}`],env,timeout:60000});
const report={passed:false,root,checks:[],errors:[],requests:[],popups:0};
try{
  report.system=await application.evaluate(({app})=>({packaged:app.isPackaged,version:app.getVersion(),appPath:app.getAppPath(),gpu:app.getGPUFeatureStatus().gpu_compositing}));
  assert.equal(report.system.packaged,Boolean(staged));
  const page=await application.waitForEvent('window', {predicate:page=>page.url().startsWith('http://127.0.0.1:'),timeout:30000}).catch(()=>application.windows().find(page=>page.url().startsWith('http://127.0.0.1:')));
  assert.ok(page);
  page.setDefaultTimeout(15000);
  page.on('pageerror',e=>report.errors.push(e.message));
  page.on('popup',()=>report.popups++);
  await page.locator('nav').waitFor();
  const address=new URL(page.url()).origin;
  await application.evaluate(({shell})=>{global.__revealedMedia=[];shell.showItemInFolder=target=>global.__revealedMedia.push(target);});
  const nav=name=>page.locator('nav').getByRole('button',{name,exact:true});
  await nav('Hàng đợi').click();
  await page.getByRole('button',{name:'Hoàn tất',exact:true}).click();
  const first=page.locator('.job-card').first();
  assert.equal(await first.getAttribute('data-job-id'),recent[0].id);
  assert.match(await first.innerText(),/Hoàn tất lúc/);
  assert.match(await first.innerText(),/Nguồn:/);
  await first.getByRole('button',{name:/Xem video/}).click();
  const dialog=page.getByRole('dialog');
  await dialog.waitFor();
  const video=dialog.locator('video');
  await page.waitForFunction(()=>document.querySelector('[role="dialog"] video')?.currentTime>0.15);
  assert.equal(await video.getAttribute('src'),`/api/media/${recent[0].mediaId}/file`);
  await video.evaluate(async el=>{el.pause();el.currentTime=10;await el.play();});
  await page.waitForFunction(()=>document.querySelector('[role="dialog"] video')?.currentTime>10.15);
  report.playedSeconds=await video.evaluate(el=>el.currentTime);
  await dialog.getByRole('button',{name:'Chọn đúng tệp trong thư mục',exact:true}).click();
  await dialog.locator('code').waitFor();
  const actualPath=await fs.realpath(source.media.find(m=>m.id===recent[0].mediaId).file);
  assert.equal(await dialog.locator('code').innerText(),actualPath);
  assert.deepEqual(await application.evaluate(()=>global.__revealedMedia),[actualPath]);
  await page.screenshot({path:path.join(root,'queue-play.png')});
  await dialog.getByRole('button',{name:'Đóng',exact:true}).click();
  assert.equal(report.popups,0);
  report.checks.push('Electron Queue completion plays the correct final MP4 inline, advances time and seeks without opening a popup');
  report.checks.push('Reveal targets the exact physical video file through the data junction');

  await nav('Thư viện').click();
  await page.locator('.library-page').waitFor();
  const groups=page.getByLabel('Nhóm kho media');
  const cards=page.locator('.media-card');
  assert.equal(await cards.count(),3);
  const displayed=await cards.evaluateAll(els=>els.map(el=>el.dataset.mediaId));
  assert.deepEqual(new Set(displayed),new Set(recent.map(job=>job.mediaId)));
  await groups.getByRole('button',{name:/^Avatar Page/}).click();
  assert.equal(await cards.count(),store.state.media.filter(m=>m.mediaType==='page-avatar').length);
  assert.equal(await cards.getByRole('button',{name:'Soạn Content',exact:true}).count(),0);
  await groups.getByRole('button',{name:/^Ảnh MC/}).click();
  assert.equal(await cards.count(),3);
  await groups.getByRole('button',{name:/^Video MC thô/}).click();
  assert.equal(await cards.count(),3);
  report.checks.push('Library defaults to three final outputs and separates Page avatars, MC stills and raw presenter clips');

  await nav('Research & News').click();
  await page.getByLabel('Ngày đăng nguồn').selectOption('24h');
  assert.equal(await page.locator('.research-result-card').count(),1);
  await page.getByRole('button',{name:/^Tất cả \/ lịch sử/}).click();
  await page.getByLabel('Ngày đăng nguồn').selectOption('older');
  const old=store.state.researchResults.filter(r=>r.articles.every(a=>!a.publishedAt||Date.parse(a.publishedAt)<Date.now()-86400000));
  assert.equal(await page.locator('.research-result-card').count(),old.length);
  await page.getByLabel('Ngày đăng nguồn').selectOption('all');
  report.checks.push('Source-age filter distinguishes old news from newly completed renders and displays source date separately');

  await page.route('**/api/production/batches',async route=>{
    if(route.request().method()!=='POST')return route.continue();
    const request=route.request().postDataJSON();report.requests.push(request);
    await route.fulfill({status:202,contentType:'application/json',body:JSON.stringify({id:randomUUID(),items:Array.from({length:request.count},()=>({status:'pending'}))})});
  });
  const card=page.locator(`[data-research-id="${fresh.id}"]`);
  const selectedMc=recent[0].payload.avatarMediaId;
  await card.getByRole('button', { name: 'Chi tiết & MC', exact: true }).click();
  await card.getByLabel('Ảnh MC cho tin này',{exact:true}).selectOption(selectedMc);
  assert.equal(await card.getByLabel('Ảnh MC cho tin này').locator('option').filter({hasText:'Page Avatar'}).count(),0);
  await card.getByLabel('Số video',{exact:true}).fill('3');
  await card.getByRole('button',{name:'Render 3 videos',exact:true}).click();
  await page.locator('.render-hub').waitFor();
  assert.equal(report.requests.at(-1).avatarMediaId,selectedMc);
  assert.equal(report.requests.at(-1).count,3);
  assert.equal(report.requests.at(-1).researchId,fresh.id);
  assert.equal(report.requests.at(-1).accountId,'auto');
  report.checks.push('Research individual story sends the selected MC and requested three videos, separate from the provider profile');

  await nav('Research & News').click();
  // Navigation refreshes state asynchronously; Render has the same MC label.
  // Target Research so a fast test action cannot select the departing page's MC.
  const researchPage=page.locator('.research-page');
  const batchMc=researchPage.getByLabel('Ảnh MC cho cả lô',{exact:true});
  await batchMc.selectOption(selectedMc);
  await researchPage.getByLabel('Số video mỗi tin',{exact:true}).fill('2');
  assert.equal(await batchMc.inputValue(),selectedMc,'Fast selection must survive initial Research mount');
  await page.getByRole('button',{name:'Render 1 tin chưa có video · 2 video',exact:true}).click();
  await page.locator('.render-hub').waitFor();
  assert.equal(report.requests.at(-1).avatarMediaId,selectedMc);
  assert.equal(report.requests.at(-1).count,2);
  assert.deepEqual(report.requests.at(-1).researchIds,[fresh.id,fresh.id]);
  report.checks.push('Research bulk render sends one common MC and two videos per selected unfinished story');

  const upload=page.locator('.production-panel').getByLabel('Nhập ảnh MC',{exact:true});
  const avatar=source.media.find(m=>m.id===selectedMc);
  await upload.setInputFiles(avatar.file);
  await page.waitForFunction(()=>document.querySelector('.production-panel .production-mc-picker select')?.value);
  const uploadedId=await page.getByLabel('Ảnh MC cho cả lô',{exact:true}).inputValue();
  assert.notEqual(uploadedId,selectedMc);
  const snapshot=await(await fetch(address+'/api/state')).json();
  assert.equal(snapshot.media.find(m=>m.id===uploadedId)?.mediaType,'news-mc');
  await page.getByLabel('Number of videos',{exact:true}).fill('4');
  await page.screenshot({path:path.join(root,'mc-selection.png')});
  report.checks.push('Importing an MC image immediately selects it and stores it under the MC group');
  assert.deepEqual(report.errors,[]);
  report.passed=true;
}catch(error){report.failure=error.stack;process.exitCode=1;}
finally{
  await application.close();
  await fs.writeFile(path.resolve('.verification/media-flow-ui-report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify({...report,requests:report.requests.map(({count,avatarMediaId,researchId})=>({count,avatar:avatarMediaId?.slice(0,8),research:researchId?.slice(0,8)}))},null,2));
}
