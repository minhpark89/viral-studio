import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { chromium } from 'playwright';
import { Store } from '../server/store.js';
import { startServer } from '../server/index.js';
import { createContentFromMedia } from '../server/content.js';

const root = path.resolve('.verification', `content-inventory-ui-${Date.now()}`);
const seed = new Store(path.join(root, 'data')), project = seed.createProject('Content inventory QA');
seed.state.settings.queuePaused = true;
seed.state.settings.content.autoPublishNews = false;
const researchId = randomUUID();
seed.state.researchResults = [{ id: researchId, projectId: project.id, headline: 'Repeated source title', articles: [{ title: 'Source report', url: 'https://example.invalid/report', source: 'Test source', summary: 'The source confirms an update.' }] }];
const videos = Array.from({ length: 230 }, (_, i) => ({ id: randomUUID(), projectId: project.id, name: 'News · Repeated title.mp4', kind: 'video', generated: true, mediaType: 'news-video', duration: 15, createdAt: new Date(Date.UTC(2026, 10, 16, 0, 0, i)).toISOString(), production: { contentType: 'news', researchId, title: 'Repeated title' } }));
seed.state.media = videos;
seed.state.socialPosts = videos.slice(0, 91).map(m => ({ id: randomUUID(), projectId: project.id, contentType: 'news', title: 'Repeated title', caption: 'Existing content', articleBody: 'Existing article', firstComment: 'https://example.invalid/existing', website: { status: 'published', url: 'https://example.invalid/existing' }, status: 'draft', revision: 1, mediaIds: [m.id], researchId }));
seed.save();
const originalFetch = globalThis.fetch;
let externalAttempts = 0;
globalThis.fetch = async (input, init) => { const url = new URL(typeof input === 'string' || input instanceof URL ? input : input.url); if (['127.0.0.1', 'localhost'].includes(url.hostname)) return originalFetch(input, init); externalAttempts++; throw Error('External access disabled during Content QA'); };
const studio = await startServer({ port: 0, dataDir: seed.root });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.setDefaultTimeout(20000);
const checks = [], errors = [], requests = [];
page.on('pageerror', error => errors.push(error.message));
let mode = 'fail-one', active = 0, peak = 0, failId = '', websiteErrorId = '';
const inbox = page.getByRole('region', { name: 'Video chưa có Content', exact: true });
const until = async (check, label) => { for (let i = 0; i < 200; i++) { if (await check()) return; await page.waitForTimeout(50); } throw Error(`Timeout: ${label}`); };
const options = { articleReader: async () => 'The source confirms an update.', llm: async () => ({ title: 'Generated article', caption: 'A verified update.', firstComment: 'Learn more about this product.', articleBody: 'The source confirms the development and gives readers the available details. The report explains the context and identifies what has been confirmed. Additional developments remain unknown and readers should consult the original source for further information.' }) };
try {
  await page.route('**/*', route => { const url = new URL(route.request().url()); if (url.protocol === 'data:' || ['127.0.0.1', 'localhost'].includes(url.hostname)) return route.continue(); externalAttempts++; return route.abort(); });
  await page.route('**/api/content/from-media/*', async route => {
    const id = route.request().url().split('/').at(-1);
    requests.push(id); active++; peak = Math.max(peak, active);
    try {
      await new Promise(resolve => setTimeout(resolve, mode === 'stop' ? 800 : 15));
      if (mode === 'fail-one' && id === failId) return await route.fulfill({ status: 503, json: { error: 'Synthetic LLM error' } });
      let post = await createContentFromMedia(studio.store, id, { ...route.request().postDataJSON(), options });
      if (id === websiteErrorId) post = studio.store.patch('socialPosts', post.id, { automationStatus: 'website_error', automationError: 'Synthetic website error' });
      await route.fulfill({ status: 201, json: post });
    } catch (error) { await route.fulfill({ status: error.status || 500, json: { error: error.message } }); }
    finally { active--; }
  });
  await page.goto(studio.address);
  await page.locator('nav').getByRole('button', { name: 'Content Studio', exact: true }).click();
  await inbox.getByRole('heading', { name: '139 video chưa có Content', exact: true }).waitFor();
  assert.match(await page.getByLabel('Đối chiếu video và Content').innerText(), /230 video đã render/);
  assert.match(await page.getByLabel('Đối chiếu video và Content').innerText(), /91 video đã có Content/);
  assert.equal(await inbox.locator('article').count(), 20);
  await inbox.getByLabel('Chọn tất cả 139 video', { exact: true }).check();
  assert.equal(await inbox.getByRole('button', { name: 'Tạo Content cho 139 video', exact: true }).isEnabled(), true);
  await page.getByLabel('Đối chiếu video và Content').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(root, 'counts-and-select-all.png') });
  await inbox.getByRole('button', { name: 'Trang video sau', exact: true }).click();
  assert.equal(await inbox.locator('article input:checked').count(), 20);
  await inbox.locator('article input').first().uncheck();
  assert.equal(await inbox.getByLabel('Chọn tất cả 139 video', { exact: true }).evaluate(el => el.indeterminate), true);
  await inbox.getByLabel('Chọn tất cả 139 video', { exact: true }).check();
  for (let i = 0; i < 5; i++) await inbox.getByRole('button', { name: 'Trang video sau', exact: true }).click();
  assert.equal(await inbox.locator('article').count(), 19);
  assert.equal(await inbox.locator('article input:checked').count(), 19);
  await page.screenshot({ path: path.join(root, 'all-139-selected.png'), fullPage: false });
  checks.push('All 139 distinct videos counted; selecting all spans seven pages, including same-title/same-research variants');

  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await inbox.evaluate(el => el.scrollWidth > el.clientWidth), false);
  await inbox.locator('.content-inbox-controls').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(root, 'mobile.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  checks.push('Inbox controls and video rows fit the mobile viewport');

  await inbox.getByLabel('Chọn tất cả 139 video', { exact: true }).uncheck();
  assert.equal(await inbox.getByRole('button', { name: 'Tạo Content cho 0 video', exact: true }).isDisabled(), true);
  await inbox.locator('article input').nth(0).check();
  await inbox.locator('article input').nth(1).check();
  failId = await inbox.locator('article').nth(1).getAttribute('data-video-id');
  await inbox.getByRole('button', { name: 'Tạo Content cho 2 video', exact: true }).click();
  await until(() => studio.store.state.socialPosts.length === 92 && !active, 'one saved and one failed');
  await inbox.getByText('Đã xử lý: 2/2 video', { exact: true }).waitFor();
  assert.equal(await inbox.getByRole('button', { name: 'Tạo Content cho 1 video', exact: true }).isEnabled(), true);
  mode = 'success';
  await inbox.getByRole('button', { name: 'Tạo Content cho 1 video', exact: true }).click();
  await until(() => studio.store.state.socialPosts.length === 93 && !active, 'failed video retried');
  await inbox.getByText('Đã xử lý: 1/1 video', { exact: true }).waitFor();
  assert.equal(studio.store.state.socialPosts.filter(p => p.mediaIds?.includes(failId)).length, 1);
  checks.push('Only selected videos are created; failed video remains selected and retries once without duplicating saved content');

  mode = 'stop';
  await inbox.getByLabel('Chọn tất cả 137 video', { exact: true }).check();
  const beforeStop = requests.length;
  await inbox.getByRole('button', { name: 'Tạo Content cho 137 video', exact: true }).click();
  await until(() => active === 2, 'two requests started');
  await inbox.getByRole('button', { name: 'Dừng sau video đang xử lý', exact: true }).click();
  await inbox.getByText('Đã dừng: 2/137 video', { exact: true }).waitFor();
  assert.equal(requests.length - beforeStop, 2);
  assert.equal(studio.store.state.socialPosts.length, 95);
  checks.push('Stopping waits for the two active requests and sends no further videos');

  mode = 'success';
  const remaining = videos.filter(m => !studio.store.state.socialPosts.some(p => p.mediaIds?.includes(m.id)));
  websiteErrorId = remaining[0].id;
  await inbox.getByRole('button', { name: 'Tạo Content cho 135 video', exact: true }).click();
  await until(() => studio.store.state.socialPosts.length === 230 && !active, 'all remaining content created');
  await inbox.getByText('Đã xử lý: 135/135 video', { exact: true }).waitFor();
  assert.match(await inbox.innerText(), /1 lỗi website/);
  assert.equal(peak, 2);
  assert.equal(new Set(studio.store.state.socialPosts.flatMap(p => p.mediaIds)).size, 230);
  assert.match(await page.getByLabel('Đối chiếu video và Content').innerText(), /0 video chưa có Content/);
  assert.equal(studio.store.state.settings.content.autoPublishNews, false);
  checks.push('All remaining selected videos complete with bounded concurrency; a website error is reported separately from saved Content');
  await page.reload();
  await page.locator('nav').getByRole('button', { name: 'Content Studio', exact: true }).click();
  await until(async () => /230 video đã có Content/.test(await page.getByLabel('Đối chiếu video và Content').innerText()), 'saved content after reload');
  assert.equal(await inbox.count(), 0);
  const other = studio.store.createProject('Other project QA');
  const otherVideos = Array.from({ length: 5 }, () => ({ ...videos[0], id: randomUUID(), projectId: other.id, name: 'Product test.mp4', mediaType: 'product-video', production: { contentType: 'product', title: 'Product test' } }));
  studio.store.state.media.push(...otherVideos); studio.store.save();
  await page.locator('.project-select select').selectOption(other.id);
  await inbox.getByLabel('Chọn tất cả 5 video', { exact: true }).check();
  mode = 'stop'; const beforeLeave = requests.length;
  await inbox.getByRole('button', { name: 'Tạo Content cho 5 video', exact: true }).click();
  await until(() => active === 2, 'other project batch started');
  await page.locator('nav').getByRole('button', { name: 'News Studio', exact: true }).click();
  await until(() => !active, 'active requests complete after navigating');
  await page.locator('nav').getByRole('button', { name: 'Content Studio', exact: true }).click();
  await inbox.getByRole('heading', { name: '3 video chưa có Content', exact: true }).waitFor();
  assert.equal(requests.length - beforeLeave, 2);
  assert.equal(await inbox.getByRole('button', { name: 'Tạo Content cho 0 video', exact: true }).isDisabled(), true);
  checks.push('Project selection is isolated; leaving Content stops unsent requests and saved results survive navigation');
  assert.equal(externalAttempts, 0); assert.deepEqual(errors, []);
  checks.push('Reload preserves 230 distinct Content attachments and an empty inbox; no external requests');
  await fs.writeFile(path.join(root, 'report.json'), JSON.stringify({ passed: true, checks, errors, externalAttempts, peak, posts: studio.store.state.socialPosts.length, requests: requests.length }, null, 2));
  console.log(JSON.stringify({ passed: true, root, checks }, null, 2));
} catch (error) {
  await page.screenshot({ path: path.join(root, 'failure.png') }).catch(() => {});
  await fs.writeFile(path.join(root, 'report.json'), JSON.stringify({ passed: false, checks, errors, externalAttempts, error: error.stack }, null, 2));
  console.error(error.stack); console.log(root); process.exitCode = 1;
} finally { await browser.close(); await studio.close(); globalThis.fetch = originalFetch; }
