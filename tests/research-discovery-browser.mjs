import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import { Store } from '../server/store.js';
import { startServer } from '../server/index.js';

const root = path.resolve('../.maintenance/release-091-20261104/research-ui');
await fs.mkdir(root, { recursive: true });
const seed = new Store(path.join(root, `data-${Date.now()}`));
seed.createProject('Adaptive Research QA'); seed.state.settings.queuePaused = true; seed.save();
const originalFetch = globalThis.fetch;
let available = 23, externalWrites = 0, feeds = 0;
globalThis.fetch = async (input, options = {}) => {
  const url = new URL(typeof input === 'string' || input instanceof URL ? input : input.url);
  if (['127.0.0.1', 'localhost'].includes(url.hostname)) return originalFetch(input, options);
  if (options.method && options.method !== 'GET') externalWrites++;
  if (url.hostname !== 'news.google.com') throw Error(`Unexpected external request: ${url.hostname}`);
  feeds++;
  const count = url.searchParams.get('q').startsWith('donal ') ? 23 : available;
  const rss = `<rss><channel><title>Research QA</title>${Array.from({ length: count }, (_, i) => `<item><title>Trump war diplomacy report ${i}</title><link>https://qa.test/news/${i}</link><description>Ceasefire negotiations and military diplomacy.</description><source>Outlet ${i % 4}</source><pubDate>${new Date(Date.now() - 3_600_000).toUTCString()}</pubDate></item>`).join('')}</channel></rss>`;
  await new Promise(resolve => setTimeout(resolve, 40));
  return new Response(rss);
};
const studio = await startServer({ port: 0, dataDir: seed.root });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], checks = []; page.on('pageerror', error => errors.push(error.message));
const until = async (fn, label) => { for (let i = 0; i < 300; i++) { if (await fn()) return; await page.waitForTimeout(100); } throw Error(`Timeout: ${label}`); };
try {
  await page.goto(studio.address);
  await page.getByRole('button', { name: 'Research & News', exact: true }).click();
  await page.getByLabel('Chủ đề cần nghiên cứu', { exact: true }).fill('donal trump wars');
  await page.getByLabel('Số tin muốn research', { exact: true }).fill('50');
  assert.equal(await page.getByLabel('Số tin muốn research', { exact: true }).getAttribute('max'), '1000');
  assert.equal(await page.getByLabel('Độ mới của tin', { exact: true }).inputValue(), '24');
  await page.getByRole('button', { name: 'Bắt đầu research', exact: true }).click();
  await until(() => studio.store.state.researchBatches[0]?.status === 'partial', '23/50 partial result');
  const panel = page.locator('[data-research-batch-id]').first();
  await panel.getByRole('button', { name: 'Tìm tiếp phần thiếu (27 tin)', exact: true }).waitFor();
  assert.equal(await panel.locator('progress').getAttribute('max'), '50');
  assert.equal(await panel.locator('progress').getAttribute('value'), '23');
  const previousIds = studio.store.state.researchResults.map(result => result.id);
  await page.screenshot({ path: path.join(root, 'partial-23-of-50.png'), fullPage: true });
  checks.push('50 requested; source exhaustion shows 23/50 and an actionable 27-story refill');
  available = 50;
  await panel.getByRole('button', { name: 'Tìm tiếp phần thiếu (27 tin)', exact: true }).click();
  await until(() => studio.store.state.researchBatches[0].status === 'completed', '50/50 saved');
  await until(async () => await panel.locator('progress').getAttribute('value') === '50', 'completed UI');
  assert.deepEqual(studio.store.state.researchResults.slice(0, 23).map(result => result.id), previousIds);
  assert.equal(studio.store.state.researchResults.length, 50);
  await panel.locator('summary').filter({ hasText: 'Gợi ý từ khóa' }).click();
  assert.ok(await panel.locator('.research-keyword-list button').count() > 0);
  await panel.locator('summary').filter({ hasText: 'Đã tìm' }).click();
  assert.ok(await panel.locator('.research-discovery-details li').count() > 1);
  await page.screenshot({ path: path.join(root, 'completed-50-of-50.png'), fullPage: true });
  await panel.screenshot({ path: path.join(root, 'batch-panel.png') });
  checks.push('Refill preserves 23 saved IDs and completes 50; keywords and actual queries are visible');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(root, 'mobile.png'), fullPage: true });
  assert.equal(externalWrites, 0); assert.deepEqual(errors, []);
  checks.push('Responsive layout; no JavaScript errors or external writes');
  await fs.writeFile(path.join(root, 'report.json'), JSON.stringify({ passed: true, checks, feeds, externalWrites, errors }, null, 2));
  console.log(JSON.stringify({ passed: true, root, checks }));
} catch (error) {
  await page.screenshot({ path: path.join(root, 'failure.png'), fullPage: true }).catch(() => {});
  await fs.writeFile(path.join(root, 'report.json'), JSON.stringify({ passed: false, error: error.stack, checks, errors }, null, 2));
  throw error;
} finally { await browser.close(); await studio.close(); globalThis.fetch = originalFetch; }
